    @Override
    public ValidatePostingBatchRequest recalculateClaimsStage0(RecalculateClaimsRequest request) {
        return ValidatePostingBatchRequest.newBuilder()
                .setContext(request.getContext())
                .setPostingBatch(PostingBatch.newBuilder()
                        .setBillingAddress(PostalAddress.newBuilder()
                                .addAllLines(request.getDetails().getDestination().getLinesList())
                                .build())
                        .setCounterparty(LedgerAccountRef.newBuilder()
                                .setDisplayName(request.getClaim().getAssignee().getDisplayName())
                                .build())
                        .build())
                .build();
    }
